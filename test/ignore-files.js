// Characterization tests for the `ignoreFiles` option, the only user of
// `multimatch`. The expectations were recorded against multimatch@5 and held
// unchanged on v6; v7 (minimatch 9) differs only where noted inline. Keep them:
// they make a future multimatch/minimatch bump a pass/fail check.
import { createRequire } from 'node:module';

import postcss from 'postcss';
import { test } from 'tap';

import DoIUse from '../lib/DoIUse.js';

const css = 'body { display: flex; }';

/**
 * @param {string} from
 * @param {string[]} ignoreFiles
 * @param {(options: ConstructorParameters<typeof DoIUse>[0])
 *   => import('postcss').AcceptedPlugin} [create]
 * @return {Promise<boolean>} true when the file's usages were ignored
 */
async function isIgnored(from, ignoreFiles, create = (options) => new DoIUse(options)) {
  let called = false;
  await postcss(create({
    browsers: ['ie 6'],
    ignoreFiles,
    onFeatureUsage() { called = true; },
  }))
    .process(css, { from });
  return !called;
}

// postcss resolves `from` to an absolute path, so matching is always against
// an absolute path. [from, ignoreFiles, expected ignored]
/** @type {[string, string[], boolean][]} */
const cases = [
  // plain globs
  ['/p/src/a.css', ['**/a.css'], true],
  ['/p/src/a.css', ['**/b.css'], false],
  ['/p/src/a.css', ['/p/src/a.css'], true],
  ['/p/src/a.css', ['/p/src/*.css'], true],
  ['/p/src/deep/a.css', ['/p/src/*.css'], false],
  ['/p/src/deep/a.css', ['/p/src/**/*.css'], true],
  ['/p/src/a.css', ['*.css'], false],
  ['/p/src/a.css', ['a.css'], false],
  ['/p/src/a.css', ['src/**/*.css'], false],
  ['/p/src/a.css', ['**/*.scss'], false],
  ['/p/src/a.css', ['**/A.CSS'], false],
  ['/p/src/a.css', [], false],
  // several patterns: any match ignores
  ['/p/src/a.css', ['**/b.css', '**/a.css'], true],
  ['/p/src/a.css', ['**/b.css', '**/c.css'], false],
  // braces, classes, extglobs
  ['/p/src/a.css', ['**/{a,b}.css'], true],
  ['/p/src/c.css', ['**/{a,b}.css'], false],
  ['/p/src/a.css', ['**/[ab].css'], true],
  ['/p/src/a.css', ['**/?.css'], true],
  ['/p/src/ab.css', ['**/?.css'], false],
  ['/p/src/a.css', ['**/@(a|b).css'], true],
  ['/p/src/a.css', ['**/!(a).css'], false],
  ['/p/src/b.css', ['**/!(a).css'], true],
  // minimatch >= 6 collapses `x/..` segments in patterns
  ['/p/src/a.css', ['/p/src/{a,b}/../a.css'], true],
  // dot segments are not matched by * or **
  ['/p/.hidden/a.css', ['**/a.css'], false],
  ['/p/.hidden/a.css', ['/p/.hidden/a.css'], true],
  ['/p/.hidden/a.css', ['**/.hidden/a.css'], true],
  ['/p/src/.a.css', ['**/*.css'], false],
  // node_modules is a common real-world pattern
  ['/p/node_modules/lib/n.css', ['**/node_modules/**'], true],
  ['/p/node_modules/lib/n.css', ['**/node_modules/**/*.css'], true],
  ['/p/src/n.css', ['**/node_modules/**'], false],
  // negation (a lone/leading negation excludes nothing from an empty result)
  ['/p/src/a.css', ['!**/a.css'], false],
  ['/p/src/b.css', ['!**/a.css'], false],
  ['/p/src/a.css', ['**/*.css', '!**/a.css'], false],
  ['/p/src/b.css', ['**/*.css', '!**/a.css'], true],
  ['/p/src/a.css', ['!**/a.css', '**/*.css'], true],
  ['/p/src/b.css', ['!**/a.css', '**/*.css'], true],
  // comments / escaping
  ['/p/src/#a.css', ['#**/a.css'], false],
  ['/p/src/a.css', ['\\/p/src/a.css'], false],
  ['/p/src/a[1].css', ['**/a\\[1\\].css'], true],
  ['/p/src/a[1].css', ['**/a[1].css'], false],
  // unicode and spaces
  ['/p/s rc/ä.css', ['**/ä.css'], true],
  ['/p/s rc/ä.css', ['**/s rc/*.css'], true],
];

test('ignoreFiles glob semantics', async (t) => {
  for (const [from, ignoreFiles, expected] of cases) {
    t.equal(
      // eslint-disable-next-line no-await-in-loop
      await isIgnored(from, ignoreFiles),
      expected,
      `${from} vs ${JSON.stringify(ignoreFiles)} => ${expected ? 'ignored' : 'reported'}`,
    );
  }
});

test('ignoreFiles works through the CommonJS build', async (t) => {
  const require = createRequire(import.meta.url);
  // exports/*.cjs is generated by `npm run prepare` (rollup)
  // non-literal so tsc doesn't type-check the bundle
  const cjsPath = '../exports/index.cjs';
  // eslint-disable-next-line import/no-dynamic-require
  const doiuse = require(cjsPath);
  t.equal(await isIgnored('/p/src/a.css', ['**/a.css'], doiuse), true);
  t.equal(await isIgnored('/p/src/a.css', ['**/b.css'], doiuse), false);
});
